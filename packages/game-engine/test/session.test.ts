import {afterEach, describe, expect, it} from "vitest";
import {createServer, type Server} from "node:http";
import {WalletStore} from "../../../apps/server/src/wallet.js";
import {createApi} from "../../../apps/server/src/api.js";
import {GoogleAuthFlow} from "../../../apps/server/src/google-auth.js";

describe("guest HTTP session", () => {
  let server:Server;
  let store:WalletStore;
  afterEach(async()=>{if(server) await new Promise<void>(resolve=>server.close(()=>resolve()));store?.close();});
  it("issues a protected cookie and restores the same wallet", async () => {
    store=new WalletStore(":memory:");
    server=createServer(createApi(store));
    await new Promise<void>(resolve=>server.listen(0,"127.0.0.1",resolve));
    const url=`http://127.0.0.1:${(server.address() as {port:number}).port}`;
    const first=await fetch(url+"/api/session",{method:"POST",headers:{origin:"http://127.0.0.1:5173"}});
    expect(first.status).toBe(200);
    const cookie=first.headers.get("set-cookie")!;
    expect(cookie).toContain("HttpOnly");
    expect(cookie).toContain("SameSite=Lax");
    expect(await first.json()).toMatchObject({balance:10000});
    const second=await fetch(url+"/api/session",{headers:{cookie:cookie.split(";")[0]!}});
    expect(second.status).toBe(200);
    expect(await second.json()).toMatchObject({balance:10000});
    expect((await fetch(url+"/api/grant",{method:"POST",headers:{origin:"https://evil.example",cookie}})).status).toBe(403);
  });
  it("accepts only the configured public origin and protects HTTPS session cookies",async()=>{
    store=new WalletStore(":memory:");
    server=createServer(createApi(store,"https://poker.example"));
    await new Promise<void>(resolve=>server.listen(0,"127.0.0.1",resolve));
    const url=`http://127.0.0.1:${(server.address() as {port:number}).port}`;
    const allowed=await fetch(url+"/api/session",{method:"POST",headers:{origin:"https://poker.example"}});
    expect(allowed.status).toBe(200);
    expect(allowed.headers.get("set-cookie")).toContain("Secure");
    expect((await fetch(url+"/api/session",{method:"POST",headers:{origin:"http://127.0.0.1:5173"}})).status).toBe(403);
  });
  it("completes Google authorization only in the initiating guest session",async()=>{
    store=new WalletStore(":memory:");
    let nonce="";
    const flow=new GoogleAuthFlow(store,{authorizationUrl:args=>{nonce=args.nonce;return `https://example.test/?state=${args.state}`;},verifyCode:async()=>({sub:"google-123",nonce,name:"Google Test"})});
    server=createServer(createApi(store,"http://127.0.0.1:5173",flow));
    await new Promise<void>(resolve=>server.listen(0,"127.0.0.1",resolve));
    const url=`http://127.0.0.1:${(server.address() as {port:number}).port}`;
    const session=await fetch(url+"/api/session",{method:"POST",headers:{origin:"http://127.0.0.1:5173"}});
    const original=await session.json() as {id:string};
    const cookie=session.headers.get("set-cookie")!.split(";")[0]!;
    const start=await fetch(url+"/api/auth/google/start",{method:"POST",redirect:"manual",headers:{origin:"http://127.0.0.1:5173",cookie}});
    expect(start.status).toBe(302);
    const state=new URL(start.headers.get("location")!).searchParams.get("state");
    const callback=await fetch(url+`/api/auth/google/callback?state=${state}&code=example`,{redirect:"manual",headers:{cookie}});
    expect(callback.status).toBe(302);
    expect(callback.headers.get("location")).toBe("/?auth=success");
    const newCookie=callback.headers.get("set-cookie")!.split(";")[0]!;
    const restored=await fetch(url+"/api/session",{headers:{cookie:newCookie}});
    expect(await restored.json()).toMatchObject({id:original.id,balance:10000,accountType:"google",googleName:"Google Test"});
    const replay=await fetch(url+`/api/auth/google/callback?state=${state}&code=example`,{redirect:"manual",headers:{cookie}});
    expect(replay.headers.get("location")).toBe("/?auth=error");
  });
  it("restores a guest wallet after switching to an existing Google account",async()=>{
    store=new WalletStore(":memory:");
    const googleOwner=store.createGuest(),guest=store.createGuest();
    store.loginGoogle(googleOwner.id,"existing-google");
    let nonce="";
    const flow=new GoogleAuthFlow(store,{authorizationUrl:args=>{nonce=args.nonce;return `https://example.test/?state=${args.state}`;},verifyCode:async()=>({sub:"existing-google",nonce})});
    server=createServer(createApi(store,"http://127.0.0.1:5173",flow));
    await new Promise<void>(resolve=>server.listen(0,"127.0.0.1",resolve));
    const url=`http://127.0.0.1:${(server.address() as {port:number}).port}`,origin="http://127.0.0.1:5173";
    const start=await fetch(url+"/api/auth/google/start",{method:"POST",redirect:"manual",headers:{origin,cookie:`poker_session=${guest.token}`}});
    const state=new URL(start.headers.get("location")!).searchParams.get("state");
    const callback=await fetch(url+`/api/auth/google/callback?state=${state}&code=example`,{redirect:"manual",headers:{cookie:`poker_session=${guest.token}`}});
    const cookies=callback.headers.getSetCookie().map(cookie=>cookie.split(";")[0]).join("; ");
    expect(cookies).toContain("poker_guest_backup=");
    expect((await fetch(url+"/api/auth/guest",{method:"POST",redirect:"manual",headers:{origin:"https://evil.example",cookie:cookies}})).status).toBe(403);
    store.reserve(googleOwner.id,"room",1000);
    expect((await fetch(url+"/api/auth/guest",{method:"POST",redirect:"manual",headers:{origin,cookie:cookies}})).headers.get("location")).toBe("/?auth=error");
    store.cashOut(googleOwner.id);
    const back=await fetch(url+"/api/auth/guest",{method:"POST",redirect:"manual",headers:{origin,cookie:cookies}});
    expect(back.headers.get("location")).toBe("/?auth=guest");
    const restored=back.headers.get("set-cookie")!.split(";")[0]!;
    const profile=await fetch(url+"/api/session",{headers:{cookie:restored}});
    expect(await profile.json()).toMatchObject({id:guest.id,balance:10000,accountType:"guest"});
  });
});
