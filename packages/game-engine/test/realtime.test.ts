import {afterEach,describe,expect,it} from "vitest";
import {createServer, type Server as HttpServer} from "node:http";
import {io as connect, type Socket} from "socket.io-client";
import {WalletStore} from "../../../apps/server/src/wallet.js";
import {createApi} from "../../../apps/server/src/api.js";
import {attachRealtime} from "../../../apps/server/src/realtime.js";
import {mkdtempSync,rmSync} from "node:fs";
import {join} from "node:path";
import {tmpdir} from "node:os";

describe("authenticated realtime rooms",()=>{
  let store:WalletStore, server:HttpServer, clients:Socket[]=[];
  afterEach(async()=>{for(const client of clients)client.disconnect();if(server)await new Promise<void>(r=>server.close(()=>r()));store?.close();clients=[];});
  it("uses account wallets, rejects duplicate commands and restores the same seat after disconnect",async()=>{
    store=new WalletStore(":memory:");
    const a=store.createGuest(),b=store.createGuest(),c=store.createGuest();
    server=createServer(createApi(store));
    const realtime=attachRealtime(server,store,Buffer.alloc(32,3),"http://192.168.1.10:5173");
    await new Promise<void>(r=>server.listen(0,"127.0.0.1",r));
    const url=`http://127.0.0.1:${(server.address() as {port:number}).port}`;
    const client=(token:string)=>{const socket=connect(url,{forceNew:true,transports:["websocket"],extraHeaders:{origin:"http://192.168.1.10:5173",cookie:`poker_session=${token}`}});clients.push(socket);return socket;};
    const waitConnect=(s:Socket)=>new Promise<void>((resolve,reject)=>{s.once("connect",()=>resolve());s.once("connect_error",reject);});
    const first=client(a.token),second=client(b.token);await Promise.all([waitConnect(first),waitConnect(second)]);
    const create=await first.timeout(2000).emitWithAck("room:create","Alice");
    expect(create.ok).toBe(true);
    const guessing=client(c.token);await waitConnect(guessing);
    const wrong=create.room==="AAAAAA" ? "BBBBBB" : "AAAAAA";
    for(let i=0;i<12;i++)expect((await guessing.timeout(2000).emitWithAck("room:join",wrong,"Guess")).ok).toBe(false);
    guessing.disconnect();
    const retry=client(c.token);await waitConnect(retry);
    expect((await retry.timeout(2000).emitWithAck("room:join",create.room,"Guess")).ok).toBe(false);
    expect((await first.timeout(1000).emitWithAck("friends:invite",b.id)).ok).toBe(false);
    const friendsA=await first.timeout(2000).emitWithAck("friends:list");
    const friendsB=await second.timeout(2000).emitWithAck("friends:list");
    expect(friendsA.ok).toBe(true);
    expect((await second.timeout(1000).emitWithAck("profile:name","Боб")).ok).toBe(true);
    expect(store.displayName(b.id)).toBe("Боб");
    const requested=await first.timeout(2000).emitWithAck("friends:request",friendsB.code);
    expect(requested.ok).toBe(true);
    const inbox=await second.timeout(2000).emitWithAck("friends:list");
    expect(inbox.requests).toHaveLength(1);
    expect((await first.timeout(2000).emitWithAck("friends:accept",inbox.requests[0].id)).ok).toBe(false);
    expect((await second.timeout(2000).emitWithAck("friends:accept",inbox.requests[0].id)).ok).toBe(true);
    expect((await first.timeout(2000).emitWithAck("friends:list")).friends).toEqual([expect.objectContaining({id:b.id,online:true})]);
    const invitation=new Promise<unknown>(resolve=>second.once("friend:invite",resolve));
    expect((await first.timeout(2000).emitWithAck("friends:invite",b.id)).ok).toBe(true);
    expect(await invitation).toEqual({fromId:a.id,fromName:"Alice",room:create.room});
    expect((await first.timeout(2000).emitWithAck("friends:remove",b.id)).ok).toBe(true);
    expect((await second.timeout(2000).emitWithAck("friends:list")).friends).toEqual([]);
    expect((await second.timeout(2000).emitWithAck("room:join",create.room,"Bob")).ok).toBe(true);
    expect(store.balance(a.id)).toBe(0);
    const start=await first.timeout(2000).emitWithAck("room:advance",create.room);
    expect(start.ok).toBe(true);
    expect((await second.timeout(2000).emitWithAck("room:action",create.room,start.handId,start.version,{type:"check"})).ok).toBe(false);
    first.disconnect();
    const again=client(a.token);await waitConnect(again);
    const resumed=await again.timeout(2000).emitWithAck("room:resume");
    expect(resumed.ok).toBe(true);
    expect(resumed.room).toBe(create.room);
    const fold=await again.timeout(2000).emitWithAck("room:action",create.room,start.handId,start.version,{type:"fold"});
    expect(fold.ok).toBe(true);
    expect((await again.timeout(2000).emitWithAck("history:list")).hands).toEqual([expect.objectContaining({handId:start.handId,change:-50})]);
    expect((await second.timeout(2000).emitWithAck("history:list")).hands).toEqual([expect.objectContaining({handId:start.handId,change:50})]);
    expect((await again.timeout(2000).emitWithAck("room:action",create.room,start.handId,start.version,{type:"fold"})).ok).toBe(false);
    expect((await again.timeout(2000).emitWithAck("room:leave")).ok).toBe(true);
    expect((await second.timeout(2000).emitWithAck("room:leave")).ok).toBe(true);
    expect(store.balance(a.id)).toBe(9950);
    expect(store.balance(b.id)).toBe(10050);
    realtime.close();
  });
  it("restores a hand and settles balances after a server restart",async()=>{
    const dir=mkdtempSync(join(tmpdir(),"poker-realtime-test-")),path=join(dir,"poker.sqlite"),key=Buffer.alloc(32,5);
    let realtime:ReturnType<typeof attachRealtime>|undefined;
    try {
      store=new WalletStore(path);
      const a=store.createGuest(),b=store.createGuest();
      const boot=async()=>{
        server=createServer(createApi(store));realtime=attachRealtime(server,store,key);
        await new Promise<void>(r=>server.listen(0,"127.0.0.1",r));
        return `http://127.0.0.1:${(server.address() as {port:number}).port}`;
      };
      const connectWith=async(url:string,token:string)=>{
        const socket=connect(url,{forceNew:true,transports:["websocket"],extraHeaders:{origin:"http://127.0.0.1:5173",cookie:`poker_session=${token}`}});
        clients.push(socket);await new Promise<void>((resolve,reject)=>{socket.once("connect",()=>resolve());socket.once("connect_error",reject);});return socket;
      };
      let url=await boot();
      let first=await connectWith(url,a.token),second=await connectWith(url,b.token);
      const created=await first.timeout(2000).emitWithAck("room:create","Alice");
      expect(created.ok).toBe(true);
      expect((await second.timeout(2000).emitWithAck("room:join",created.room,"Bob")).ok).toBe(true);
      const started=await first.timeout(2000).emitWithAck("room:advance",created.room);
      expect((await first.timeout(2000).emitWithAck("room:action",created.room,started.handId,started.version,{type:"call"})).ok).toBe(true);
      first.disconnect();second.disconnect();realtime!.close();
      await new Promise<void>(r=>server.close(()=>r()));store.close();
      store=new WalletStore(path);url=await boot();
      first=await connectWith(url,a.token);second=await connectWith(url,b.token);
      expect((await first.timeout(2000).emitWithAck("room:resume")).room).toBe(created.room);
      expect((await second.timeout(2000).emitWithAck("room:resume")).room).toBe(created.room);
      const recovery=store.loadHand(started.handId,key)!;
      expect(recovery.version).toBe(started.version+1);
      expect((await second.timeout(2000).emitWithAck("room:action",created.room,started.handId,recovery.version,{type:"fold"})).ok).toBe(true);
      expect((await first.timeout(2000).emitWithAck("room:leave")).ok).toBe(true);
      expect((await second.timeout(2000).emitWithAck("room:leave")).ok).toBe(true);
      expect(store.balance(a.id)).toBe(10100);
      expect(store.balance(b.id)).toBe(9900);
    } finally {
      for(const client of clients)client.disconnect();clients=[];
      realtime?.close();
      if(server)await new Promise<void>(r=>server.close(()=>r()));
      store?.close();store=undefined as unknown as WalletStore;
      rmSync(dir,{recursive:true,force:true});
    }
  });
});
